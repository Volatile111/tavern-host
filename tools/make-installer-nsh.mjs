// Writes desktop/installer.nsh with tools/installer-check.ps1 embedded (PowerShell -EncodedCommand: base64 UTF-16LE),
// so the installer can run it before any files are unpacked.   node tools/make-installer-nsh.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const script = readFileSync(path.join(root, 'tools', 'installer-check.ps1'), 'utf-8');
const encoded = Buffer.from(script, 'utf16le').toString('base64');

const nsh = `; Generated by tools/make-installer-nsh.mjs from tools/installer-check.ps1 - edit those, not this file.
; Before installing: close the panel window and background service, but never game-server runners, so game servers
; keep running through an update. Servers started by old versions (runner inside Tavern Host.exe) must be stopped
; first, because that file can't be replaced while they run.
!macro customInit
  nsExec::ExecToStack 'powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -EncodedCommand ${encoded}'
  Pop $0
  Pop $1
  StrCmp $0 "2" 0 +3
    MessageBox MB_ICONSTOP|MB_OK "Some Minecraft servers are running under the old version of Tavern Host.$\\r$\\n$\\r$\\nStop your Java and Bedrock servers in Tavern Host (their worlds are saved), then run this installer again. After this update, servers keep running through future updates." /SD IDOK
    Abort
!macroend
`;
writeFileSync(path.join(root, 'desktop', 'installer.nsh'), nsh);
console.log(`desktop/installer.nsh written (${encoded.length} chars of script)`);
